function block(selector: string) {
  const escaped = selector.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  const match = css.match(new RegExp(`${escaped}\\s*\\{([\\s\\S]*?)\\}`))
  if (!match) throw new Error(`Missing CSS block: ${selector}`)
  return match[1]
}

function exactBlock(selector: string) {
  const escaped = selector.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  const match = css.match(new RegExp(`(?:^|\\n)${escaped}\\s*\\{([\\s\\S]*?)\\}`))
  if (!match) throw new Error(`Missing exact CSS block: ${selector}`)
  return match[1]
}

function declaration(cssBlock: string, property: string) {
  const escaped = property.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  const match = cssBlock.match(new RegExp(`${escaped}:\\s*([^;]+);`))
  if (!match) throw new Error(`Missing CSS declaration: ${property}`)
  return match[1].trim()
}

function rgbaAlpha(value: string) {
  const match = value.match(/^rgba\([^,]+,[^,]+,[^,]+,\s*([.\d]+)\)$/)
  if (!match) throw new Error(`Expected rgba() value, got ${value}`)
  return Number(match[1])
}

function pxDeclaration(cssBlock: string, property: string) {
  const value = declaration(cssBlock, property)
  const match = value.match(/^(-?\d+(?:\.\d+)?)px$/)
  if (!match) throw new Error(`Expected ${property} to be a px value, got ${value}`)
  return Number(match[1])
}

function paddingRight(cssBlock: string) {
  const parts = declaration(cssBlock, 'padding').split(/\s+/)
  if (parts.length !== 4) throw new Error(`Expected four-value padding, got ${parts.join(' ')}`)
  const match = parts[1].match(/^(-?\d+(?:\.\d+)?)px$/)
  if (!match) throw new Error(`Expected right padding to be px, got ${parts[1]}`)
  return Number(match[1])
}

function paddingLeft(cssBlock: string) {
  const parts = declaration(cssBlock, 'padding').split(/\s+/)
  if (parts.length !== 4) throw new Error(`Expected four-value padding, got ${parts.join(' ')}`)
  const match = parts[3].match(/^(-?\d+(?:\.\d+)?)px$/)
  if (!match) throw new Error(`Expected left padding to be px, got ${parts[3]}`)
  return Number(match[1])
}

function variables(selector: string) {
  const entries: Array<[string, string]> = []
  for (const match of block(selector).matchAll(/--([\w-]+):\s*([^;]+);/g)) {
    entries.push([match[1], match[2].trim()])
  }
  return Object.fromEntries(entries)
}

function resolveToken(tokens: Record<string, string>, name: string) {
  let value = tokens[name]
  const seen = new Set<string>()
  while (value?.startsWith('var(--')) {
    const match = value.match(/^var\(--([\w-]+)\)$/)
    if (!match || seen.has(match[1])) break
    seen.add(match[1])
    value = tokens[match[1]]
  }
  return value
}

